"""Curated native draw-to-asset binding; rejects ambiguous geometry signatures.

No runtime VB identity is asserted. Runtime admission also requires the exact
captured unskinned VS/PS, declaration and proven native constant semantics.
"""
import hashlib
import json
import struct
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT/'renderer')]
import northlight_paths as fp
fp.use_source_modules()
from world_scene_builder import Assets, array, skin_vertex_indices, blp_mips
from build_outdoor_single_sun import texture_names
from build_sky_material_catalog import fnv

assets = Assets()
provenance, textures, candidates, families = {}, {}, {}, []
def read(path):
    data = assets.read(path)
    provenance[path] = {'sha256': hashlib.sha256(data).hexdigest(), 'archive': assets.origin(path)}
    return data
def texture(path):
    if path in textures:
        return textures[path]
    blob = read(path)
    if blob[8] != 2:
        return None
    for _, w, h, start, size in blp_mips(blob):
        if max(w,h)==32:
            textures[path] = fnv(blob[start:start+size])
            return textures[path]
    return None
try:
    dbc = read('dbfilesclient\\lightskybox.dbc')
    rows, fields, stride, _ = struct.unpack_from('<4I', dbc, 4)
    strings = dbc[20+rows*stride:]
    models=set()
    for i in range(rows):
        off=struct.unpack_from('<I',dbc,20+i*stride+4)[0]
        path=strings[off:].split(b'\0')[0].decode().lower()
        if path: models.add(path[:-4]+'.m2')
    for path in sorted(models):
        model=read(path);names,lookup=texture_names(model)
        if not any(n.rsplit('\\',1)[-1].startswith('auroralight') for n in names):continue
        n,off=struct.unpack_from('<II',model,60);vertices=array(model,off,n,'<3f4B4B3f4f')
        for skin_id in range(struct.unpack_from('<I',model,68)[0]):
            skin_path=path[:-3]+f'{skin_id:02d}.skin'
            try:skin=read(skin_path)
            except FileNotFoundError:continue
            n,off=struct.unpack_from('<II',skin,28);subsets=array(skin,off,n,'<10H7f')
            n,off=struct.unpack_from('<II',skin,36);batches=array(skin,off,n,'<2B11H')
            indices=skin_vertex_indices(model,skin);family=[]
            for batch in batches:
                if batch[8]!=2:continue
                name=names[lookup[batch[9]]]
                if not name.rsplit('\\',1)[-1].startswith('auroralight'):continue
                first_hash,second_hash=texture(name),texture(names[lookup[batch[9]+1]])
                if first_hash is None or second_hash is None:continue
                subset=subsets[batch[3]];first=subset[4]+(subset[1]<<16);count=subset[5]
                key=(first_hash,second_hash,first,subset[2],subset[3],count//3)
                data=tuple(tuple(0.0 if x==0 else x for x in (*vertices[i][:3],*vertices[i][14:18])) for i in indices[first:first+count])
                packed=b''.join(struct.pack('<7f',*v) for v in data)
                digest=hashlib.sha256(packed).hexdigest()
                candidates.setdefault(key,{})[digest]=data
                family.append(key)
            if family:families.append((path,skin_id,family))
    good={key:next(iter(values.values())) for key,values in candidates.items() if len(values)==1}
    keys=sorted(good);key_ids={key:i for i,key in enumerate(keys)}
    # Aliases with identical emitting subsets are one supported mesh family.
    groups=sorted(set(tuple(sorted(key_ids[k] for k in family)) for _,_,family in families if all(k in good for k in family)))
    def number(value):
        text=format(value,'.9g')
        return text+('f' if any(c in text for c in '.eE') else '.0f')
    lines=['// Generated by build_aurora_asset_data.py; curated draw signatures, not GPU buffer proof.','#pragma once','#include <cstdint>',
           'namespace NorthlightAuroraNative {','struct AssetVertex {float position[3],uv[2][2];};',
           'inline constexpr AssetVertex AssetVertices[]={']
    offsets={};payloads={};vertex_ids={};emitter_indices=[];cursor=0
    for key in keys:
        if good[key] in payloads:
            offsets[key]=payloads[good[key]]
            continue
        offsets[key]=cursor
        payloads[good[key]]=cursor
        for v in good[key]:
            if v not in vertex_ids:
                vertex_ids[v]=len(vertex_ids)
                lines.append('    {{'+','.join(map(number,v[:3]))+'},{{'+','.join(map(number,v[3:5]))+'},{'+','.join(map(number,v[5:]))+'}}},')
            emitter_indices.append(vertex_ids[v])
        cursor+=len(good[key])
    lines+=['};','inline constexpr unsigned AssetIndices[]={']
    lines+=['    '+','.join(map(str,emitter_indices[i:i+24]))+',' for i in range(0,len(emitter_indices),24)]
    lines+=['};','struct AssetBatch {std::uint64_t firstTexture,secondTexture;unsigned first,minimum,vertices,primitives,offset;};','inline constexpr AssetBatch AssetBatches[]={']
    for key in keys:lines.append('    {0x%016xull,0x%016xull,%d,%d,%d,%d,%d},'%(*key,offsets[key]))
    lines+=['};','struct AssetFamily {unsigned offset,count;};','inline constexpr unsigned AssetFamilyBatches[]={']
    lines+=['    '+','.join(map(str,g))+',' for g in groups];lines+=['};','inline constexpr AssetFamily AssetFamilies[]={'];cursor=0
    for group in groups:lines.append(f'    {{{cursor},{len(group)}}},');cursor+=len(group)
    lines+=['};','}']
    target=fp.GENERATED/'aurora_asset_data.h';target.write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    manifest={'inputs':provenance,'unique_batch_signatures':len(keys),'families':len(groups),'ambiguous_signatures':len(candidates)-len(good),
              'header_sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'models':[{'path':p,'skin':s,'emitter_batches':len(f)} for p,s,f in families]}
    (ROOT/'src/sky/aurora-asset-build.json').write_text(json.dumps(manifest,indent=2)+'\n', encoding='utf-8', newline='\n')
    print({k:manifest[k] for k in ['unique_batch_signatures','families','ambiguous_signatures']},'header_bytes',target.stat().st_size)
finally:
    assets.close()
