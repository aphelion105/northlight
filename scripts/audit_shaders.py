"""Inventory offline shader bytecode and its source references; not a GPU cost model.

References are lexical evidence, not proof of runtime reachability. Identical
bytecode may have several symbols. Review callers before removing an entry.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import northlight_paths as fp


def inventory():
    arrays = {}
    sizes = {}
    pattern = re.compile(r'(?:static|inline)\s+(?:const|constexpr)\s+(?:DWORD|std::uint32_t)\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};', re.S)
    for path in sorted(fp.GENERATED.glob('*compiled_shaders.h')):
        for symbol, body in pattern.findall(path.read_text()):
            words = [int(word, 16) for word in re.findall(r'0x([0-9a-fA-F]+)', body)]
            data = struct.pack('<' + 'I' * len(words), *words)
            digest = hashlib.sha256(data).hexdigest()
            sizes[digest] = len(data)
            arrays.setdefault(digest, []).append((symbol, path.relative_to(ROOT).as_posix()))

    references = {}
    for directory in (fp.SRC, fp.TESTS):
        for path in sorted(directory.rglob('*')):
            if path.suffix not in ('.h', '.cpp', '.inl', '.py') or fp.GENERATED in path.parents:
                continue
            for line, text in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
                for symbol in set(re.findall(r'\bk[A-Za-z0-9_]+\b', text)):
                    references.setdefault(symbol, []).append(f'{path.relative_to(ROOT).as_posix()}:{line}')

    rows = []
    for path in sorted(fp.SHADERS.glob('*shader-build.json')):
        manifest = json.loads(path.read_text())
        for entry, info in manifest['shaders'].items():
            symbols = arrays.get(info['sha256'])
            if not symbols:
                raise ValueError(f'{path.name}/{entry}: no matching generated bytecode')
            refs = sorted({ref for symbol, _ in symbols for ref in references.get(symbol, [])})
            runtime = [ref for ref in refs if ref.startswith('src/')]
            rows.append(dict(manifest=path.name, entry=entry, symbols=symbols,
                             bytes=sizes[info['sha256']], sha256=info['sha256'],
                             slots=info.get('static_instruction_slots'),
                             temporaries=info.get('temporary_registers'),
                             samplers=info.get('samplers'),
                             instructions=info.get('instructions'),
                             runtime_references=runtime,
                             test_references=[ref for ref in refs if ref.startswith('tests/')],
                             status='runtime-reference' if runtime else 'review-no-runtime-reference'))
    sources = {p.relative_to(ROOT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
               for p in sorted(fp.SHADERS.glob('*.hlsl'))}
    return dict(scope='Offline manifest entries only. Dynamic native shader patches and fixed-function draws require a separate audit. Static slots do not estimate executed loops or GPU time.',
                sources=sources, entries=rows)


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--output', type=Path, default=fp.output_dir() / 'shader-audit')
    args = parser.parse_args()
    report = inventory()
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'inventory.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    lines = ['| Manifest / entry | Slots / temps | Bytes | Runtime reference |',
             '|---|---:|---:|---|']
    for row in report['entries']:
        refs = row['runtime_references']
        lines.append(f"| {row['manifest']} / {row['entry']} | {row['slots']} / {row['temporaries']} | {row['bytes']} | {refs[0] if refs else 'REVIEW: no lexical reference'} |")
    (args.output / 'inventory.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f"{len(report['entries'])} entries; {len(report['sources'])} HLSL sources; {args.output}")
    for row in report['entries']:
        if not row['runtime_references']:
            print('REVIEW', row['manifest'], row['entry'])


if __name__ == '__main__':
    main()
