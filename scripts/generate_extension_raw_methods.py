"""Generate private extension fast paths; never alter game-facing guards."""
from pathlib import Path
import re
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import northlight_paths  # noqa: E402
CONTROL = {'BeginStateBlock', 'EndStateBlock', 'CreateStateBlock', 'Reset', 'SetSoftwareVertexProcessing', 'SetNPatchMode'}
# 0.3.149: not mirrored, so they already went straight to the backend. Counted
# pass-through overrides only (per-type call counts on sampled frames). The mock
# test API has no such methods, so they are left out of that build.
COUNTED = ['Clear', 'StretchRect', 'ColorFill', 'SetScissorRect', 'SetTextureStageState']
AUXILIARY_BOUNDARIES = {'Clear', 'ColorFill', 'StretchRect', 'UpdateSurface', 'UpdateTexture',
                        'GetRenderTargetData', 'GetFrontBufferData', 'BeginScene', 'EndScene',
                        'Present', 'ValidateDevice', 'DrawRectPatch', 'DrawTriPatch'}
AUXILIARY_BARRIER = 'if(!m->finishDeferredTargets())return E_FAIL;'

def generated():
    mirror = northlight_paths.src('device_mirror.h').read_text().split('class MirrorDevice :')[1].split('// Extension calls')[0]
    selected = set(re.findall(r'HRESULT STDMETHODCALLTYPE (\w+)\([^\n]*?override', mirror)) - CONTROL
    # Controls retain mirror recording/failure/Apply behavior even inside raw scopes.
    forwarders = northlight_paths.src('forwarders.h').read_text().split('class ForwardIDirect3DDevice9 :')[1].split('\n};')[0]
    lines = ['// Generated by generate_extension_raw_methods.py. Included inside ExtensionDevice.']
    found, names, counted = set(), [], {}
    def barrier(name):
        if name == 'QueryInterface': return ''  # ExtensionDevice returns itself.
        if name == 'SetRenderState': return 'indexedRaster(State);'
        if name == 'GetRenderState': return 'observeIndexedStencil(State);'
        if name == 'SetVertexShaderConstantF': return 'indexedFloats(reg_idx, data, count);'
        if name == 'SetTexture': return 'indexedTexture(Stage,pTexture);'
        if name.startswith('Get') and name not in {'GetRenderTargetData','GetFrontBufferData','GetBackBuffer'}: return ''
        return 'indexedBarrier();'
    for line in forwarders.splitlines():
        name = re.search(r'HRESULT STDMETHODCALLTYPE (\w+)\(', line)
        if name and name.group(1) in COUNTED:
            counted[name.group(1)] = line
        if not name or name.group(1) not in selected:
            continue
        found.add(name.group(1))
        signature, call = line.split('{ return real->', 1)
        call = call.removesuffix(' }')
        lines.append(signature + '{ ' + barrier(name.group(1)) + 'if(rawActive()){++m->rawCalls;m->countRaw(' + str(len(names)) + ');return real->' + call + '}return MirrorDevice::' + call + ' }')
        names.append(name.group(1))
    assert found == selected, (found, selected)
    assert len(found) == 39, len(found)
    assert sorted(counted) == sorted(COUNTED), counted
    lines.append('#ifndef NORTHLIGHT_DEVICE_MIRROR_TEST_API')
    for name in COUNTED:
        signature, call = counted[name].split('{ return real->', 1)
        lines.append(signature + '{ ' + barrier(name) + (AUXILIARY_BARRIER if name in AUXILIARY_BOUNDARIES else '') + 'if(m->rawCounting&&rawActive())m->countRaw(' + str(len(names)) + ');return real->' + call.removesuffix(' }') + ' }')
        names.append(name)
    for line in forwarders.splitlines():
        method = re.search(r'HRESULT STDMETHODCALLTYPE (\w+)\(', line)
        if not method or method.group(1) in selected or method.group(1) in COUNTED or not barrier(method.group(1)):
            continue
        name = method.group(1)
        signature, call = line.split('{ return real->', 1)
        target = 'MirrorDevice::' if name in CONTROL else 'real->'
        lines.append(signature + '{ indexedBarrier();' + (AUXILIARY_BARRIER if name in AUXILIARY_BOUNDARIES else '') + 'return '+ target + call)
    lines.append('#endif')
    lines.append('    static constexpr unsigned RawMethods=' + str(len(names)) + ';')
    lines.append('    static_assert(RawMethods<=DeviceMirror::RawMethodCapacity,"raw method counters");')
    lines.append('    static const char* rawMethodName(unsigned i){static const char* const names[RawMethods]={' + ','.join('"' + n + '"' for n in names) + '};return i<RawMethods?names[i]:"";}')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    path = northlight_paths.GENERATED / 'extension_raw_methods.inl'
    data = generated().encode('utf-8')
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)
