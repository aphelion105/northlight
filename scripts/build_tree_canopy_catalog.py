#!/usr/bin/env python3
"""Fingerprint reviewed cutout textures used by the Elwynn and Ashenvale tree models."""
import sys
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from renderer.world_scene_builder import Assets, blp_mips, decode_blp


# These batches were reviewed on the stock and installed trees. Some trunk
# batches also use alpha testing, so blend mode alone cannot identify foliage.
TEXTURES = {
    r'world\azeroth\elwynn\passivedoodads\trees\elwynntreecanopy_leaves01.blp',
    r'world\generic\human\passive doodads\stormwind\elwynntreetallcanopy_new01.blp',
    r'world\expansion07\doodads\ashenvale\8ash_gianttreecanopy01.blp',
    r'world\expansion07\doodads\ashenvale\8ash_treecanopy01.blp',
    r'world\expansion07\doodads\ashenvale\8ash_greentreecanopy01.blp',
    r'world\expansion07\doodads\ashenvale\8ash_tree_b01_1_2320084.blp',
    r'world\expansion04\doodads\valleyoffourwinds\junglecanopytree\dsw_junglecanopytree_canopy.blp',
    r'world\expansion04\doodads\valleyoffourwinds\junglecanopytree\dfw_junglecanopytree_canopy.blp',
    r'world\expansion04\doodads\valleyoffourwinds\junglecanopytree\sh_junglecanopytree_canopy.blp',
    r'world\kalimdor\kalidar\passivedoodads\kalidartrees\stranglethorntree_leaves_set_color.blp',
    r'world\expansion02\doodads\scholazar\trees\sholazarleaves_new01.blp',
    r'dungeons\textures\trees\kalidartreeneedles_final.blp',
    r'dungeons\textures\trees\kalidartreeneedles_small01.blp',
    r'dungeons\textures\trees\kalidarfattree01.blp',
    r'dungeons\textures\trees\kalidartree_fatleaf_purple.blp',
    r'dungeons\textures\trees\kalidatmidtreeleaf01.blp',
}


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value


def fingerprints(assets):
    for path in sorted(TEXTURES & assets.providers.keys()):
        blob = assets.read(path)
        encoding, alpha, alpha_format = struct.unpack_from('<3B', blob, 8)
        for _, w, h, offset, size in blp_mips(blob):
            if min(w, h) < 16 or max(w, h) > 1024:
                continue
            if encoding == 2:
                fmt = 0x31545844 if alpha <= 1 else 0x33545844 if alpha_format == 1 else 0x35545844
                rows, row_bytes = (h+3)//4, (w+3)//4*(8 if alpha <= 1 else 16)
                data = blob[offset:offset+size]
            elif encoding == 3:
                fmt, rows, row_bytes = 21, h, w*4
                data = blob[offset:offset+size]
            else:
                fmt, rows, row_bytes = 21, h, w*4
                rw, rh, rgba = decode_blp(blob, max(w, h))
                assert (rw, rh) == (w, h)
                data = bytearray(rgba)
                data[0::4], data[2::4] = rgba[2::4], rgba[0::4]
            at = rows//3*row_bytes+row_bytes//3
            bt = (2*rows//3)*row_bytes+row_bytes//3
            yield (fnv(data[at:at+8]+data[bt:bt+8]), fmt, w, h, fnv(data))


if __name__ == '__main__':
    rows = set()
    for view in ('stock', 'all'):
        assets = Assets(archives=view)
        try:
            rows.update(fingerprints(assets))
        finally:
            assets.close()
    assert rows
    rows = sorted(rows)
    header = ['// Generated by scripts/build_tree_canopy_catalog.py.', '#pragma once',
              'inline constexpr CanopyMip canopyMips[]={']
    header += [f'    {{0x{prefix:016x}ull,0x{digest:016x}ull,0x{fmt:08x}u,{w},{h}}},'
               for prefix, fmt, w, h, digest in rows]
    header += ['};', '']
    (ROOT/'src/generated/tree_canopy_catalog.h').write_text('\n'.join(header), encoding='ascii', newline='\n')
    print(f'{len(rows)} canopy mip signatures')
