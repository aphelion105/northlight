#!/usr/bin/env python3
"""Assemble the relocation-free x86 glue selector; --check verifies the header."""
from pathlib import Path
import argparse
import struct
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import northlight_paths as fp


def generate():
    obj = fp.output_dir() / 'glue-lighting-selection.obj'
    subprocess.run([str(fp.zig()), 'cc', '-target', 'x86-windows-gnu', '-c',
                    str(fp.REPO / 'scripts/glue_lighting_selection.S'), '-o', str(obj)],
                   env=fp.zig_env(), check=True)
    blob = obj.read_bytes()
    machine, sections, _, symbols, count, optional, _ = struct.unpack_from('<HHIIIHH', blob)
    if machine != 0x14c or optional:
        raise ValueError('Expected an x86 COFF object')
    text = None
    for i in range(sections):
        at = 20 + 40 * i
        if blob[at:at+8].rstrip(b'\0') != b'.text':
            continue
        size, offset = struct.unpack_from('<II', blob, at+16)
        if struct.unpack_from('<H', blob, at+32)[0]:
            raise ValueError('Thunk must not contain relocations')
        text = blob[offset:offset+size]
    if text is None:
        raise ValueError('Missing code section')
    strings = symbols + count * 18
    found = {}
    i = 0
    while i < count:
        at = symbols + i * 18
        name = blob[at:at+8]
        if name[:4] == b'\0'*4:
            start = strings + struct.unpack_from('<I', name, 4)[0]
            name = blob[start:blob.index(b'\0', start)]
        found[name.rstrip(b'\0').decode('ascii')] = struct.unpack_from('<I', blob, at+8)[0]
        i += 1 + blob[at+17]
    entry = found['_extra_entry']
    if found['_selection'] != 0 or text[entry-1:entry+4] != b'\xb8\0\0\0\0':
        raise ValueError('Invalid native getter patch site')
    rows = [','.join(f'0x{b:02x}' for b in text[i:i+16]) for i in range(0, len(text), 16)]
    return ('#pragma once\n// Generated by scripts/generate_glue_lighting_selection.py.\n'
            'namespace NorthlightGlueLighting {\ninline constexpr unsigned char Selection[]={\n    ' +
            ',\n    '.join(rows) + '\n};\n' +
            f'inline constexpr unsigned ExtraEntryOffset={entry};\n}}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    header = fp.REPO / 'src/generated/glue_lighting_selection_code.h'
    result = generate()
    if args.check:
        if header.read_text(encoding='utf-8') != result:
            raise SystemExit('Stale glue lighting selector; regenerate it')
    else:
        header.write_text(result, encoding='utf-8', newline='\n')
