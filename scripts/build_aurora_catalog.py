"""Record native aurora material candidates from the active read-only MPQs.

This catalog prefilters candidates only. A texture identity alone cannot authorize
replacement or prove that every batch of the selected sky model was observed.
"""
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / 'renderer')]
import northlight_paths as fp
fp.use_source_modules()
from world_scene_builder import Assets, blp_mips, decode_blp
from build_sky_material_catalog import fnv


def main():
    names = json.loads((ROOT / 'src/sky/sky_material_roles.json').read_text())['materials']
    candidates = sorted(n for n in names if n.startswith('aurora'))
    records = set()
    with_assets = Assets()
    try:
        for name in candidates:
            blob = with_assets.read('environments\\stars\\' + name)
            encoding, alpha_depth, alpha_encoding = struct.unpack_from('<3B', blob, 8)
            for level, w, h, pos, size in blp_mips(blob):
                if max(w, h) > 128:
                    continue
                if encoding == 2:
                    fmt = 0x31545844 if alpha_depth <= 1 else 0x33545844 if alpha_encoding == 1 else 0x35545844
                    data = blob[pos:pos+size]
                elif encoding == 3:
                    fmt, data = 21, blob[pos:pos+size]
                else:
                    rw, rh, rgba = decode_blp(blob, max(w, h))
                    assert (rw, rh) == (w, h)
                    fmt, data = 21, bytearray(rgba)
                    data[0::4], data[2::4] = rgba[2::4], rgba[0::4]
                records.add((fnv(data), fmt, w, h))
    finally:
        with_assets.close()
    lines = ['// Generated by scripts/build_aurora_catalog.py. Candidates only; full draw/shader proof is required.',
             '#pragma once', '#include <cstdint>', 'namespace NorthlightAuroraNative {',
             'inline bool candidate(std::uint64_t hash,unsigned format,unsigned width,unsigned height){',
             '    struct Key{std::uint64_t hash;unsigned format,width,height;};',
             '    static constexpr Key keys[]={']
    lines += [f'        {{0x{h:016x}ull,{f}u,{w},{v}}},' for h, f, w, v in sorted(records)]
    lines += ['    };', '    for(const auto& k:keys)if(k.hash==hash&&k.format==format&&k.width==width&&k.height==height)return true;',
              '    return false;', '}', '}']
    target = ROOT / 'src/generated/aurora_material_candidates.h'
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{target}: {len(records)} candidate identities')


if __name__ == '__main__':
    main()
