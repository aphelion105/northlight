#!/usr/bin/env python3
"""Rebuild embedded shaders offline, with Wine or --native on Windows.

--entries=AO,AOContactBloom,AOBlur retains other verified bytecode.
No game DLL or rendering device is loaded.
"""
from pathlib import Path
import hashlib
import json
import os
import re
import struct
import subprocess
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parents[1])]  # repo root, scripts/
import northlight_paths as fp  # noqa: E402
from build_environment import wine_build_prefix, zig_env, ZIG

HERE = Path(__file__).resolve().parent   # compile_shaders.cpp and the built compile_shaders.exe


def validate_assembly(path, slot_limit=512, register_limit=32):
    """Use Microsoft's ps_3_0 slot accounting, restricted to our 2D shaders.

    https://learn.microsoft.com/en-us/windows/win32/direct3dhlsl/dx9-graphics-reference-asm-ps-instructions-ps-3-0
    Wine's compiler does not enforce the baseline 512 static slot budget.
    """
    assembly = path.read_text().rstrip("\0")
    slots = 0
    counts = {}
    costs = dict.fromkeys("abs add break cmp dp3 dp4 else endif exp expp frc log logp mad max min mov mova mul nop rcp ret rsq setp sge slt sub texld".split(), 1)
    costs.update(dict.fromkeys("call crs dp2add dsx dsy endloop endrep lrp m3x2 texkill texldl".split(), 2))
    costs.update(dict.fromkeys("breakp callnz if ifc loop m3x3 m4x3 nrm pow rep texldd texldp".split(), 3))
    costs.update(m3x4=4, m4x4=4, texldb=6, sincos=8)
    for line in assembly.splitlines():
        line = re.sub(r"^(?:/\*.*?\*/|\d+:)\s*", "", line.split("//", 1)[0].strip())
        tokens = line.split()
        if not tokens:
            continue
        op = tokens[0].split("_")[0]
        if op in {"ps", "def", "defi", "defb", "dcl", "label"}:
            continue
        if op not in costs:
            raise ValueError(f"Unknown disassembled opcode {tokens[0]}")
        cost = 3 if op == "break" and "_" in tokens[0] else costs[op]
        slots += cost
        counts[op] = counts.get(op, 0) + 1
    assert slots <= slot_limit, f"{path.name}: {slots} static instruction slots exceeds the limit {slot_limit}"
    registers = [int(n) for n in re.findall(r"\br(\d+)\b", assembly)]
    assert max(registers, default=0) < register_limit, f"{path.name}: temporary register limit exceeded"
    return {"static_instruction_slots": slots, "temporary_registers": max(registers, default=-1) + 1,
            "instructions": counts}


def main():
    native = "--native" in sys.argv
    selected = next((a.split("=", 1)[1].split(",") for a in sys.argv[1:] if a.startswith("--entries=")), None)
    if native and os.name != "nt": raise SystemExit("--native requires Windows")
    names = {"AO", "AOContactBloom", "ContactBloom", "AOBlur", "Composite", "RainMaskMRT", "RainScrub"}
    if selected and not set(selected) <= names: raise SystemExit("Unknown shader entry")
    previous = json.loads((fp.SHADERS / "shader-build.json").read_text()) if selected else None
    compiler = "Microsoft d3dcompiler_47 IEEE strict" if native else "Wine d3dcompiler_47 D3DCompile"
    env = zig_env()
    subprocess.run([
        str(ZIG), "c++",
        "-target", "x86-windows-gnu", "-O2", "-s", "-static",
        str(HERE / "compile_shaders.cpp"), "-o", str(HERE / "compile_shaders.exe"),
    ], env=env, check=True)
    if not native:
        from build_environment import WINE_ROOT
        env.update(WINEPREFIX=str(wine_build_prefix()), WINEDEBUG="-all",
                   DYLD_LIBRARY_PATH=str(WINE_ROOT / "lib/external"))
    # No game executable, game DLL, rendering device, or existing Wine prefix is used.
    chunks = ["// Generated by compile_shaders.py; do not edit.\n#pragma once\n#include <windows.h>\n"]
    manifest = {"source_sha256": hashlib.sha256((fp.SHADERS / "effects.hlsl").read_bytes()).hexdigest(),
                "rain_source_sha256": hashlib.sha256((fp.SHADERS / "rain_mask.hlsl").read_bytes()).hexdigest(),
                "target": "ps_3_0", "compiler": compiler, "game_launched": False, "shaders": {}}
    # 0.3.202 (rain mask MRT): the two rain mask pixel shaders are ps_2_0 (they pair with the game's fixed-function vertex pipeline and write
    # oC1); their manifest entries carry their own "target" and they compile from rain_mask.hlsl. The ps_3_0 entries are unchanged.
    for entry, symbol, target in (("AO", "kAoShader", "ps_3_0"), ("AOContactBloom", "kAoContactBloomShader", "ps_3_0"), ("ContactBloom", "kContactBloomShader", "ps_3_0"),
                                  ("AOBlur", "kAoBlurShader", "ps_3_0"), ("Composite", "kCompositeShader", "ps_3_0"),
                                  ("RainMaskMRT", "kRainMaskMrtShader", "ps_2_0"), ("RainScrub", "kRainScrubShader", "ps_2_0")):
        output = fp.COMPILED / f"{entry}.bin"
        assembly = fp.COMPILED / f"{entry}.bin.asm"
        compile_entry = not selected or entry in selected
        if compile_entry:
            assembly.unlink(missing_ok=True)
            command = [str(HERE / "compile_shaders.exe"),
                       str(fp.SHADERS / ("effects.hlsl" if target == "ps_3_0" else "rain_mask.hlsl")), entry, target, str(output)]
            command = command + ["--native"] if native else [str(WINE_ROOT / "bin/wine"), *command]
            subprocess.run(command, env=env, check=True, timeout=120)
        elif hashlib.sha256(output.read_bytes()).hexdigest() != previous["shaders"][entry]["sha256"]:
            raise ValueError(f"{entry}: retained bytecode differs from previous manifest")
        data = output.read_bytes()
        assert len(data) % 4 == 0, f"{entry}: non-DWORD shader length"
        words = struct.unpack(f"<{len(data)//4}I", data)
        assert words[0] == (0xFFFF0300 if target == "ps_3_0" else 0xFFFF0200), f"{entry}: expected pixel shader {target}"
        assert words[-1] == 0x0000FFFF, f"{entry}: missing END instruction"
        lines = ["    " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + ","
                 for i in range(0, len(words), 8)]
        chunks.append(f"static const DWORD {symbol}[] = {{\n" + "\n".join(lines) + "\n};\n")
        legacy = target == "ps_3_0"
        manifest["shaders"][entry] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                                      **({} if legacy else {"target": target}),
                                      **(validate_assembly(assembly) if legacy else validate_assembly(assembly, 96, 12))}
        source_key = "source_sha256" if legacy else "rain_source_sha256"
        old = previous["shaders"][entry] if not compile_entry else {}
        manifest["shaders"][entry].update(
            source_sha256=manifest[source_key] if compile_entry else old.get("source_sha256", previous[source_key]),
            compiler=compiler if compile_entry else old.get("compiler", previous.get("compiler", "Wine d3dcompiler_47 D3DCompile")))
    (fp.GENERATED / "compiled_shaders.h").write_text("\n".join(chunks))
    (fp.SHADERS / "shader-build.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
