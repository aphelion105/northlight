#!/usr/bin/env python3
"""Compile the D3D9 volume atlas kernels with the existing offline SM3 gate."""
from pathlib import Path
import hashlib
import json
import shutil
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parent)]
import northlight_paths as fp
from shader_compiler import Compiler, rows, validate_assembly

SOURCES = ('fog_volume.hlsl', 'world_effects.hlsl', 'shadow_transition.hlsl', 'auto_bump_normal.hlsl')
ENTRIES = ('VolumeInject', 'VolumeInjectQuiet', 'VolumeInjectActor', 'VolumeInjectActorQuiet', 'VolumeTemporal', 'VolumePrefix', 'VolumeResolve')


def source_hashes():
    return {name: hashlib.sha256((fp.SHADERS / name).read_bytes()).hexdigest() for name in SOURCES}


def main():
    before = source_hashes()
    compiler = Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv)
    header = ['// Generated by compile_fog_volume_shaders.py; do not edit.', '#pragma once', '#include <windows.h>']
    manifest = {'sources': before, **compiler.provenance, 'shaders': {}}
    for name in SOURCES:
        shutil.copyfile(fp.SHADERS / name, compiler.dir / name)
    for fade in (False, True):
        source = compiler.dir / 'fog_volume.hlsl'
        if fade:
            # Keep include resolution local to the production shader directory.
            source = compiler.dir / 'fog_volume_transition.hlsl'
            source.write_text('#define VOLUME_TRANSITION 1\n#include "fog_volume.hlsl"\n')
        for entry in ENTRIES[:4] if fade else ENTRIES:
            name = entry + ('Transition' if fade else '')
            output = fp.COMPILED / (name + '.bin')
            data, words = compiler.compile(source, entry, 'ps_3_0', output)
            stats = validate_assembly(Path(str(output) + '.asm'), 'ps_3_0', slot_limit=768 if fade else 512)
            header += [f'static constexpr unsigned k{name}ShaderSlots = {stats["static_instruction_slots"]};',
                       f'static const DWORD k{name}Shader[] = {{\n' + '\n'.join(rows(words)) + '\n};']
            manifest['shaders'][name] = {'target': 'ps_3_0', 'sha256': hashlib.sha256(data).hexdigest(), **stats}
            print(name, stats, flush=True)
    if before != source_hashes():
        raise RuntimeError('Volume shader dependencies changed during compilation')
    (fp.GENERATED / 'fog_volume_compiled_shaders.h').write_text('\n\n'.join(header) + '\n', encoding='utf-8', newline='\n')
    (fp.SHADERS / 'fog-volume-shader-build.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
