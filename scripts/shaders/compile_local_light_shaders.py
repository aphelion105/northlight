# Exact shipped r18 helpers preserve admission for unusually large materials.
LEGACY_HASHES=('bef28a69aa8fc6dc0c597f7fb161cd3582e8a450e76c1842237baa58a572a058',
               '4c68e8f34ea4fb1a503f5fc93b79f109b0ce625380772b4f4d7b3b99068df033',
               '05c840b71a7e11c8794f14a9b21acb46f6dfa33976f63da9940b67d4fb7b852a')

def hoist_native_derivatives(words):
    """Keep immutable view derivatives outside FXC's divergent range branch."""
    if not words or words[0]!=0xffff0300 or words[-1]!=0xffff:
        raise ValueError('Native derivative hoist requires complete ps_3_0')
    ops=[];offset=1
    while offset<len(words)-1:
        token=words[offset];code=token&65535
        length=1+((token>>16)&32767) if code==65534 else 1+((token>>24)&15)
        if code==65535 or offset+length>len(words)-1:
            raise ValueError('Malformed native helper instruction')
        ops.append(list(words[offset:offset+length]));offset+=length
    def kind(token):return ((token>>28)&7)|((token>>8)&24)
    used=set();inputs=set();body=False;insert=None
    for index,op in enumerate(ops):
        code=op[0]&65535
        if code==65534:continue
        if code in (31,47,48,81):
            if body:raise ValueError('Native helper declaration after executable code')
        else:
            if insert is None:insert=index
            body=True
        if code==31:
            if len(op)!=3:raise ValueError('Malformed native helper declaration')
            if kind(op[2])==1:inputs.add(op[2]&2047)
        operands=op[1:2] if code in (47,48,81) else op[2:] if code==31 else op[1:]
        used.update(w&2047 for w in operands if w&0x80000000 and kind(w)==0)
    free=[i for i in range(32) if i not in used]
    if len(free)<2 or insert is None:raise ValueError('No native derivative scratch registers')
    prefix=[];derivatives=[]
    for index,op in enumerate(ops):
        code=op[0]&65535
        if code not in (91,92):continue
        if len(op)!=3 or op[0]!=0x02000000|code:
            raise ValueError('Unsupported native derivative instruction modifiers')
        dst,src=op[1:]
        if (kind(dst)!=0 or kind(src)!=1 or src&2047 not in inputs or
            not src&0x80000000 or not dst&0x80000000 or
            src&0x0f002000 or dst&0x0ff02000 or not dst&0x000f0000):
            raise ValueError('Native derivative requires an unmodified declared INPUT')
        temp=free.pop(0)
        prefix.append([op[0],(dst&~2047)|temp,src])
        ops[index]=[0x02000001,dst,0x80e40000|temp]
        derivatives.append(code)
    if sorted(derivatives)!=[91,92]:
        raise ValueError('Native helper must contain exactly one DSX and one DSY')
    return [words[0]]+[word for op in ops[:insert]+prefix+ops[insert:] for word in op]+[0xffff]

def main():
    source=fp.SHADERS/'local_light_effects.hlsl';digest=hashlib.sha256(source.read_bytes()).hexdigest()
    compiler=Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv)
    header=['// Generated by compile_local_light_shaders.py.','#pragma once','#include <windows.h>'];manifest={"derivative_hoist_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),"bump_include_sha256":hashlib.sha256((fp.SHADERS/"auto_bump_normal.hlsl").read_bytes()).hexdigest(),'source_sha256':digest,**compiler.provenance,'game_launched':False,'device_created':False,'shaders':{}}
    for entry,target in [('LocalShadowVS','vs_3_0'),('LocalShadowPS','ps_3_0'),('LocalLighting','ps_3_0'),('LocalShadowResolve','ps_3_0'),('LocalLightingSoft','ps_3_0'),('LocalLightingPcss','ps_3_0'),('NativeLocalLighting1','ps_3_0'),('NativeLocalLighting2','ps_3_0'),('NativeLocalLighting3','ps_3_0')]+[(f'NativeLocalLightingLegacy{i}','ps_3_0') for i in (1,2,3)]:
        output=fp.COMPILED/(entry+'.bin');assembly=fp.COMPILED/(entry+'.bin.asm')
        legacy='Legacy' in entry
        if legacy:
            data,words=bytecode(output,target)
            if hashlib.sha256(data).hexdigest()!=LEGACY_HASHES[int(entry[-1])-1]:
                raise ValueError('Legacy native helper differs from the shipped r18 bytecode')
            compiler.disassemble(output,target)
        else:data,words=compiler.compile(source,entry,target,output)
        if entry.startswith('NativeLocalLighting') and not legacy:
            words=hoist_native_derivatives(words)
            data=struct.pack('<%dI'%len(words),*words);output.write_bytes(data)
            compiler.disassemble(output,target)
        stats=validate_assembly(assembly,target)
        # The shared validator handles 2D entries. Cube texldl costs 5 slots,
        # versus 2 for 2D (Microsoft ps_3_0 instruction table, note 2).
        text=assembly.read_text();cube={int(x) for x in re.findall(r'dcl_cube\s+s(\d+)',text)}
        extra=0
        for line in text.splitlines():
            match=re.match(r'\s*(?:/\*.*?\*/|\d+:)?\s*(texldl|texldp|texld)\s+.*\bs(\d+)\b',line)
            if match and int(match[2]) in cube:extra+=1 if match[1]=='texldp' else 3
        stats['static_instruction_slots']+=extra;stats['cube_instruction_extra_slots']=extra
        if stats['static_instruction_slots']>512:raise ValueError('SM3 cube instruction slot limit exceeded')
        header.append('static const DWORD k%sShader[] = {\n%s\n};'%(entry,'\n'.join(rows(words))))
        manifest['shaders'][entry]={'target':target,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),**stats}
        if legacy:manifest['shaders'][entry].update(legacy=True,origin='r18',source_sha256='8b87a40d98d79b96a3411b95fbeafaa784f6b658fd3c5ee201cdf906a459db50',compiler_sha256='4432bbd1a390874f3f0a503d45cc48d346abc3a8c0213c289f4b615bf0ee84f3')
        print(entry,stats['static_instruction_slots'],'slots',stats['temporary_registers'],'temps',flush=True)
    if hashlib.sha256(source.read_bytes()).hexdigest()!=digest:raise ValueError('Source changed during compilation')
    (fp.GENERATED/'local_light_compiled_shaders.h').write_text('\n\n'.join(header)+'\n',newline='\n')
    (fp.SHADERS/'local-light-shader-build.json').write_text(json.dumps(manifest,indent=2)+'\n',newline='\n')

if __name__=='__main__':main()
