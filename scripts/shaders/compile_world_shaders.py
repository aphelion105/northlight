#!/usr/bin/env python3
"""Compile standalone HLSL with Wine, or --native on Windows.

Does not load WoW, a game DLL, or a graphics device. The generated header and
manifest are published only after every entry passes the Shader Model 3 gate.
--entries=WorldNormals,RemovalSmooth retains other verified binaries and their provenance.
"""
from pathlib import Path
import hashlib
import json
import os
import re
import struct
import subprocess
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parents[1])]  # repo root, scripts/
import northlight_paths as fp  # noqa: E402
from build_environment import wine_build_prefix, zig_env, ZIG

HERE = Path(__file__).resolve().parent   # compile_shaders.cpp and the built compile_shaders.exe
ENTRIES = (("WorldNormals", "ps_3_0"), ("WorldLighting", "ps_3_0"), ("ActorShadow", "ps_3_0"), ("ActorTiles", "ps_3_0"), ("WorldGI", "ps_3_0"), ("WorldFog", "ps_3_0"), ("FogBlur", "ps_3_0"), ("FogClouds", "ps_3_0"), ("FogTemporal", "ps_3_0"), ("LocalDirect", "ps_3_0"), ("RemovalSmooth", "ps_3_0"), ("TemporalLight", "ps_3_0"), ("LocalFog", "ps_3_0"), ("LocalFogCombine", "ps_3_0"), ("SourceVisibilityPS", "ps_3_0"),
           ("WorldComposite", "ps_3_0"), ("ShadowVS", "vs_3_0"), ("ShadowCacheVS", "vs_3_0"),
           ("ShadowPS", "ps_3_0"), ("ShadowReplayPS", "ps_3_0"), ("ShadowUnion", "ps_3_0"))


def validate_assembly(path, target):
    """Baseline SM3 instruction slots and temporary-register limits.

    Cost references: Microsoft dx9-graphics-reference-asm-{ps,vs}-instructions-
    {ps,vs}-3-0. Only 2D texture instructions are emitted by these entries.
    """
    assembly = path.read_text().rstrip("\0")
    costs = dict.fromkeys("abs add break cmp dp3 dp4 else endif exp expp frc log logp mad max min mov mova mul nop rcp ret rsq setp sge slt sub texld".split(), 1)
    costs.update(dict.fromkeys("call crs dp2add dsx dsy endloop endrep lrp m3x2 texkill texldl".split(), 2))
    costs.update(dict.fromkeys("breakp callnz if ifc loop m3x3 m4x3 nrm pow rep texldd texldp lit sgn".split(), 3))
    costs.update(m3x4=4, m4x4=4, texldb=6, sincos=8)
    slots=0; counts={}
    for line in assembly.splitlines():
        line=line.split("//",1)[0].strip()
        if not line:continue
        # Native D3DDisassemble can add /* instruction-number */ prefixes.
        line=re.sub(r"^(?:/\*.*?\*/|\d+:)\s*", "", line)
        tokens=line.split()
        if not tokens:continue
        if tokens[0] in {"break_ne","break_lt","break_gt"}:
            operands=[s.strip() for s in line[len(tokens[0]):].split(",")]
            if len(operands)==2 and operands[0]==operands[1]:
                raise ValueError(f"{path.name}: non-exiting loop branch: {line}")
        op=tokens[0].split("_")[0]
        if op in {"ps", "vs", "def", "defi", "defb", "dcl", "label"}:continue
        if op not in costs:raise ValueError(f"Unknown opcode: {tokens[0]}")
        cost=3 if op=="break" and "_" in tokens[0] else costs[op]
        slots+=cost;counts[op]=counts.get(op,0)+1
    if slots>512:raise ValueError(f"{path.name}: {slots} static slots exceeds SM3 512")
    temps=[int(n) for n in re.findall(r"\br(\d+)\b",assembly)]
    if max(temps,default=-1)>=32:raise ValueError(f"{path.name}: temporary register limit")
    samplers=sorted({int(n) for n in re.findall(r"\bs(\d+)\b",assembly)})
    if samplers and max(samplers)>=(4 if target.startswith("vs") else 16):
        raise ValueError(f"{path.name}: sampler register limit")
    return {"static_instruction_slots":slots,"temporary_registers":max(temps,default=-1)+1,
            "samplers":samplers,"instructions":counts}


def main():
    native="--native" in sys.argv
    selected=next((a.split("=",1)[1].split(",") for a in sys.argv[1:] if a.startswith("--entries=")),None)
    if native and os.name!="nt":raise SystemExit("--native requires Windows")
    if selected and not set(selected)<=set(e for e,_ in ENTRIES):raise SystemExit("Unknown entry")
    previous=json.loads((fp.SHADERS/"world-shader-build.json").read_text()) if selected else None
    source=fp.SHADERS/"world_effects.hlsl"
    before=hashlib.sha256(source.read_bytes()).hexdigest()
    env=zig_env()
    subprocess.run([str(ZIG),"c++",
                    "-target","x86-windows-gnu","-O2","-s","-static",
                    str(HERE/"compile_shaders.cpp"),"-o",str(HERE/"compile_shaders.exe")],
                   env=env,check=True)
    if not native:
        from build_environment import WINE_ROOT
        env.update(WINEPREFIX=str(wine_build_prefix()),WINEDEBUG="-all",
                   DYLD_LIBRARY_PATH=str(WINE_ROOT/"lib/external"))
    header=["// Generated by compile_world_shaders.py; do not edit.","#pragma once","#include <windows.h>"]
    manifest={"source_sha256":before,"compiler":"Microsoft d3dcompiler_47 IEEE strict" if native else "Wine d3dcompiler_47 D3DCompile",
              "game_launched":False,"shaders":{}}
    for entry,target in ENTRIES:
        output=fp.COMPILED/f"{entry}.bin";asm=fp.COMPILED/f"{entry}.bin.asm"
        compile_entry=not selected or entry in selected
        if compile_entry:
            asm.unlink(missing_ok=True)
            command=[str(HERE/"compile_shaders.exe"),str(source),entry,target,str(output)]
            command=(command+["--native"]) if native else [str(WINE_ROOT/"bin/wine"),*command]
            subprocess.run(command,env=env,check=True,timeout=120)
        elif hashlib.sha256(output.read_bytes()).hexdigest()!=previous["shaders"][entry]["sha256"]:
            raise ValueError(f"{entry}: retained bytecode differs from its previous manifest")
        data=output.read_bytes()
        if len(data)%4:raise ValueError(f"{entry}: non-DWORD size")
        words=struct.unpack(f"<{len(data)//4}I",data)
        expected=0xfffe0300 if target.startswith("vs") else 0xffff0300
        if words[0]!=expected or words[-1]!=0xffff:raise ValueError(f"{entry}: invalid bytecode markers")
        stats=validate_assembly(asm,target)
        rows=["    "+", ".join(f"0x{w:08x}" for w in words[i:i+8])+"," for i in range(0,len(words),8)]
        header.append(f"static const DWORD k{entry}Shader[] = {{\n"+"\n".join(rows)+"\n};")
        manifest["shaders"][entry]={"target":target,"bytes":len(data),
            "sha256":hashlib.sha256(data).hexdigest(),**stats}
        if compile_entry:
            manifest["shaders"][entry].update(source_sha256=before,compiler=manifest["compiler"])
        else:
            old=previous["shaders"][entry]
            manifest["shaders"][entry].update(source_sha256=old.get("source_sha256",previous["source_sha256"]),
                                              compiler=old.get("compiler",previous["compiler"]))
        print(f"Validated {entry}: {stats['static_instruction_slots']} slots, {stats['temporary_registers']} temps",flush=True)
    if hashlib.sha256(source.read_bytes()).hexdigest()!=before:raise RuntimeError("HLSL changed while compiling")
    (fp.GENERATED/"world_compiled_shaders.h").write_text("\n\n".join(header)+"\n")
    (fp.SHADERS/"world-shader-build.json").write_text(json.dumps(manifest,indent=2)+"\n")
    print("Published world_compiled_shaders.h and world-shader-build.json")

if __name__=="__main__":main()
