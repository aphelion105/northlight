"""Compile the Northlight-owned liquid geometry mask; no client code is embedded."""
import hashlib,json,sys
from pathlib import Path
sys.path[:0]=[str(Path(__file__).resolve().parents[2]),str(Path(__file__).resolve().parent)]
import northlight_paths as fp
from shader_compiler import Compiler,rows,validate_assembly

def main():
    compiler=Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv);source=fp.SHADERS/'water_material_mask.hlsl'
    manifest={'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),**compiler.provenance,'game_launched':False,'shaders':{}}
    header=['#pragma once\n#include <windows.h>\n// Generated by compile_water_material_mask.py.\n']
    for entry,target in [('WaterMaterialMaskVS','vs_3_0'),('WaterMaterialMaskPS','ps_3_0')]:
        output=fp.COMPILED/(entry+'.bin');data,words=compiler.compile(source,entry,target,output)
        manifest['shaders'][entry]={'target':target,'sha256':hashlib.sha256(data).hexdigest(),**validate_assembly(Path(str(output)+'.asm'),target)}
        header.append('static const DWORD k'+entry+'[]={\n'+'\n'.join(rows(words))+'\n};\n')
    (fp.GENERATED/'water_material_mask_compiled.h').write_text('\n'.join(header),encoding='utf-8')
    (fp.SHADERS/'water-material-mask-build.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
if __name__=='__main__':main()
