"""Compile paired native-aurora emission epilogues, with SM resource gates."""
import hashlib
import json
from pathlib import Path
import sys
sys.path[:0] = [str(Path(__file__).resolve().parents[2]), str(Path(__file__).resolve().parents[1])]
import northlight_paths as fp
import shader_compiler as shared

compiler = shared.Compiler(allow_compatible_binary='--compatible-compiler' in sys.argv)
source = fp.SHADERS / 'aurora_emission.hlsl'
manifest = {'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(), **compiler.provenance, 'shaders': {}}
chunks = ['// Generated by compile_aurora_shaders.py.\n#pragma once\n#include <cstdint>\n']
for major in (2, 3):
    for entry in ('AuroraLinear', 'AuroraLegacy'):
        name = f'{entry}-ps_{major}_0'
        binary = fp.COMPILED / (name + '.bin')
        data, words = compiler.compile(source, entry, f'ps_{major}_0', binary)
        info = shared.validate_assembly(binary.with_suffix('.bin.asm'), f'ps_{major}_0', 64 if major == 2 else 512, 12 if major == 2 else 32)
        chunks.append(f'static constexpr std::uint32_t k{entry}Ps{major}[]={{\n')
        chunks.extend('    '+','.join(f'0x{w:08x}' for w in words[i:i+8])+',\n' for i in range(0, len(words), 8))
        chunks.append('};\n')
        manifest['shaders'][name] = dict(info, sha256=hashlib.sha256(data).hexdigest())
(fp.GENERATED/'aurora_compiled_shaders.h').write_text(''.join(chunks), encoding='utf-8', newline='\n')
(fp.SHADERS/'aurora-shader-build.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8', newline='\n')
